"""Writes rploginicons.inc (repository root) from the PNG files of this folder.

The login dialogs of the designers (rpfrmloginvcl, design_lcl/rpfrmloginlcl)
include it: the icons of the login buttons travel inside the program as byte
constants, the same way in Delphi and Free Pascal and on every platform (a
.res is only linked on Windows by the LCL units).

The PNG files are rendered from the SVG files of this folder at 20, 30 and 40
pixels (100, 150 and 200 % screens). After changing them:

    python build/loginicons/make-inc.py
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
NAMES = ['google', 'microsoft', 'apple', 'email']
SIZES = [20, 30, 40]


def const_name(name, size):
    return 'RpLoginIcon_%s_%d' % (name, size)


def main():
    out = []
    out.append('// Icons of the login buttons (Google, Microsoft, Apple, e-mail) as PNG files')
    out.append('// of 20, 30 and 40 pixels. Generated by build/loginicons/make-inc.py from the')
    out.append('// files of that folder: do not edit.')
    out.append('')
    out.append('const')
    for name in NAMES:
        for size in SIZES:
            with open(os.path.join(HERE, '%s_%d.png' % (name, size)), 'rb') as f:
                data = f.read()
            out.append('  %s: array[0..%d] of Byte = (' % (const_name(name, size), len(data) - 1))
            hexes = ['$%02X' % b for b in data]
            for i in range(0, len(hexes), 16):
                line = ','.join(hexes[i:i + 16])
                out.append('    ' + line + (',' if i + 16 < len(hexes) else ');'))
    out.append('')
    out.append('// Writes to AStream the PNG of a login icon (google, microsoft, apple, email)')
    out.append('// of ASize pixels (20, 30 or 40); False when there is none')
    out.append('function RpLoginIconPng(const AName: string; ASize: Integer; AStream: TStream): Boolean;')
    out.append('begin')
    out.append('  Result := True;')
    first = True
    for name in NAMES:
        for size in SIZES:
            c = const_name(name, size)
            out.append('  %sif (AName = \'%s\') and (ASize = %d) then' % ('' if first else 'else ', name, size))
            out.append('    AStream.WriteBuffer(%s, SizeOf(%s))' % (c, c))
            first = False
    out.append('  else')
    out.append('    Result := False;')
    out.append('end;')
    out.append('')
    with open(os.path.join(ROOT, 'rploginicons.inc'), 'w', newline='\r\n') as f:
        f.write('\n'.join(out))


if __name__ == '__main__':
    main()
